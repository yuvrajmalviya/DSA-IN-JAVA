package BASIC_JAVA;

public class ArithmaticOperations {
    static void main() {
        //integer
        int x = 12, y = 3;
        //add
        System.out.println(x+y + " is Sum of x & y");
        //subtract
        System.out.println(x-y);
        //divide
        System.out.println(x/y);
        //multiple
        System.out.println(x*y);
        //modulus
        int p = 20, q = 3;
        System.out.println(p%q);


        //double
        double a = 10, b = 20;
        System.out.println(a+b);
        a = 21.345;
        b=237.23;
        System.out.println(a*b);
    }

}
